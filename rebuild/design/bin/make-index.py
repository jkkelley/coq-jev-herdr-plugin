#!/usr/bin/env python3
"""
rebuild/design/bin/make-index.py: generate rebuild/design/index.xml from dag.md and the volume tree.

Why generated: the index lists every node with its input and output (the dag.md table, section 3) and every volume
file under nodes/ and shared/; writing that by hand would drift from the tree.
Line counts (2026-10-14, gap review R-03): N-46 (check C11) and brief C ask the index to carry each volume's kind and line count
so a reader sees which volume is near the 1000-line cap before opening it; the earlier rule here left the count out
because it changes with every edit. The count is now emitted, because the index is generated anyway and regenerated by
the same ticket that edits a volume (the second ticket to merge re-runs this script on rebase, so no merge conflict is
resolved by hand), and check.sh C11 and C17 refuse a stale count. Cost: every volume ticket also touches index.xml,
which the one-file rule allows because index.xml is a generated aggregate no ticket edits by hand.

Usage: bin/make-index.py [--check]   (--check exits 1 when the committed index differs from the generated one)
"""
import glob
import os
import re
import sys
import xml.etree.ElementTree as ET

BOOK = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BOOK_VERSION = "1.0.0"
BUMPED = "2026-10-14T06:30:00Z"

SHARED = [
    ("cut-over", "Cut-over order: the one ordered sequence from GOFACTORY to the old line retired"),
    ("status-codes", "Status code map: every code, its meaning, lamp and who acts"),
    ("record-kinds", "Record kinds registry (generated by bin/make-kinds.py from every node's status codes)"),
    ("principles", "Principles: the hard rules every volume is written against"),
    ("seat-contract", "Seat contract: one-shot runs, store access, roles, credentials, owner-side clauses"),
    ("state-store", "State store: envelope, tables, leases, flags, retention, config keys"),
    ("failure-cases", "Failure cases every node cites"),
    ("rejected-with-reason", "Sources that are sources only, and design items rejected book-wide"),
    ("command-center", "Command center: pointer volume over the G6 screens, hosting, art and look"),
]


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def nodes_from_dag():
    out = []
    with open(os.path.join(BOOK, "dag.md"), encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"^\| (N-\d\d) \| (.*?) \| (G\d) [^|]*\| (.*?) \| (.*?) \|\s*$", line)
            if m:
                out.append(m.groups())
    return out


def lines_of(rel):
    with open(os.path.join(BOOK, rel), encoding="utf-8") as fh:
        return sum(1 for _ in fh)


def volumes_for(nid):
    d = os.path.join(BOOK, "nodes", nid)
    refs = []
    for f in sorted(glob.glob(os.path.join(d, "*.xml"))):
        try:
            kind = ET.parse(f).getroot().attrib.get("kind", "node-spec")
        except ET.ParseError:
            kind = "node-spec"
        refs.append(("nodes/%s/%s" % (nid, os.path.basename(f)), kind))
    for f in sorted(glob.glob(os.path.join(d, "*.schema.json"))):
        refs.append(("nodes/%s/%s" % (nid, os.path.basename(f)), "record-schema"))
    return refs


def render():
    nodes = nodes_from_dag()
    groups = {}
    for nid, name, group, _, _ in nodes:
        groups.setdefault(group, []).append(nid)
    L = []
    a = L.append
    a('<?xml version="1.0" encoding="UTF-8"?>')
    a("<!-- GENERATED by rebuild/design/bin/make-index.py from dag.md and the volume tree; edit the generator, not this file.")
    a("     The index volume of the spec book: every node id with name, group, input, output and a pointer to each of its")
    a("     volumes; every shared volume; the DAG pointer. Validated by rebuild/design/check.sh against schema/volume.xsd. -->")
    a('<volume id="index" kind="index" version="%s" issued="%s" timezone="UTC" title="Spec book index">' % (BOOK_VERSION, BUMPED))
    a("")
    a('  <contents id="contents">')
    a('    <entry ref="pointers">Pointers: parent (the plan step), the DAG, the schema, the check</entry>')
    a('    <entry ref="purpose">Purpose and how to read the book</entry>')
    a('    <entry ref="book-version">Book version</entry>')
    a('    <entry ref="shared">Shared volumes</entry>')
    a('    <entry ref="nodes">Nodes: every DAG node with its input, output and volumes</entry>')
    a('    <entry ref="groups">Groups for parallel authors</entry>')
    a('    <entry ref="tooling">Tooling: check.sh, the XSD, the generators</entry>')
    a('    <entry ref="many-agents">Many agents at once</entry>')
    a('    <entry ref="sources">Sources</entry>')
    a("  </contents>")
    a("")
    a('  <pointers id="pointers">')
    a('    <parent href="../factory-rebuild-plan.xml#R-03"/>')
    a('    <sibling href="dag.md#2-the-dag" kind="dag">The DAG volume in Markdown with its Mermaid block</sibling>')
    a('    <dag href="dag.md#3-every-node"/>')
    a('    <shared href="schema/volume.xsd" role="schema">The one XSD family</shared>')
    a('    <shared href="check.sh" role="check">The book check</shared>')
    a('    <shared href="shared/state-store.schema.json#/$defs/envelope" role="schema">The shared record envelope</shared>')
    a("  </pointers>")
    a("")
    a('  <purpose id="purpose">')
    a("    <s>This is the index of the spec book, the single canonical design of the rebuilt factory (owner ruling C42, D14); every build ticket is cut from an anchor in this book and from nothing else.</s>")
    a("    <s>Read one volume at a time: start at the node's row below, follow its spec pointer, then the shared anchors the spec cites; a volume is 1000 lines or fewer and opens with its contents.</s>")
    a("    <s>Every node has status specified once its spec volume exists under nodes/; pending means the directory is not there yet, so sibling pointers to this index always resolve.</s>")
    a("  </purpose>")
    a("")
    a('  <edition id="book-version" value="%s" bumped="%s">A merge that changes any volume bumps this value (BOOK_VERSION in bin/make-index.py) in the same pull request; N-47 names Drive copies by it and refuses a publish of a version whose Drive manifest holds different volume hashes (drive.copy 423 version-not-bumped).</edition>' % (BOOK_VERSION, BUMPED))
    a("")
    a('  <shared-volumes id="shared">')
    for sid, desc in SHARED:
        rel = "shared/%s.xml" % sid
        if os.path.exists(os.path.join(BOOK, rel)):
            a('    <volume-ref href="%s#%s" kind="shared" lines="%d">%s</volume-ref>' % (rel, sid, lines_of(rel), esc(desc)))
    a('    <volume-ref href="shared/state-store.schema.json" kind="record-schema" lines="%d">The shared envelope every node schema should $ref</volume-ref>' % lines_of("shared/state-store.schema.json"))
    a('    <volume-ref href="shared/cleanup-registry.json" kind="registry" lines="%d">The cleanup registry (generated by bin/registry.py from every state-paths element)</volume-ref>' % lines_of("shared/cleanup-registry.json"))
    a('    <volume-ref href="shared/cleanup-registry.schema.json" kind="record-schema" lines="%d">The schema of the cleanup registry</volume-ref>' % lines_of("shared/cleanup-registry.schema.json"))
    a("  </shared-volumes>")
    a("")
    a('  <nodes id="nodes">')
    for nid, name, group, inp, outp in nodes:
        refs = volumes_for(nid)
        status = "specified" if refs else "pending"
        a('    <node id="%s" name="%s" group="%s" status="%s">' % (nid, esc(name), group, status))
        a("      <input>%s</input>" % esc(inp))
        a("      <output>%s</output>" % esc(outp))
        if refs:
            for href, kind in refs:
                anchor = "#" + nid if kind.startswith("node-") else ""
                a('      <volume-ref href="%s%s" kind="%s" lines="%d"/>' % (href, anchor, kind, lines_of(href)))
        else:
            a('      <volume-ref href="dag.md#3-every-node" kind="pending"/>')
        a("    </node>")
    a("  </nodes>")
    a("")
    a('  <groups id="groups">')
    for g in sorted(groups):
        a('    <s>%s: %s</s>' % (g, " ".join(groups[g])))
    a("    <s>One author seat per group; a node belongs to exactly one group; groups never overlap in files (dag.md section 5).</s>")
    a("  </groups>")
    a("")
    a('  <tooling id="tooling">')
    a("    <s>check.sh runs bin/check-book.py: checks C01 to C22 as listed in nodes/N-46/spec.xml#checks (well-formed, XSD, the 1000-line cap, contents, parent, pointers, many agents, no dashes, unique ids, JSON schemas, index completeness and line counts, envelope, waits, cleanup registry, record kinds, the DAG, index freshness, codes, input and output, panel bindings, examples against their schemas); one line per failure; exit 0, 1 or 2.</s>")
    a("    <s>Generators, each with --check: bin/make-index.py (this file, with a line count per volume), bin/make-kinds.py (shared/record-kinds.xml), bin/registry.py (shared/cleanup-registry.json); bin/dag-check.py checks dag.md; bin/test-checks.py proves every check fails on a mutated copy of the book. N-37 reads the nodes element to generate machines.json.</s>")
    a("    <s>schema/volume.xsd descends from rebuild/schema/factory-rebuild-plan.xsd: the same envelope (contents, ids, UTC), extended with the volume kinds and the shared vocabulary.</s>")
    a("  </tooling>")
    a("")
    a('  <many-agents id="many-agents">')
    a("    <readers>Every seat starts here; fifty can read it at once because it is generated, stateless and anchored by node id.</readers>")
    a("    <writers>Nobody edits it by hand: a node directory appearing or a dag.md row changing regenerates it in the same pull request (the generator runs in the pre-commit of a design ticket and N-46 runs --check); two tickets adding two nodes regenerate the same file, and the second to merge re-runs the generator on rebase, so the file never carries a merge conflict a human resolves.</writers>")
    a("    <collision>Two tickets claiming one node directory are refused at readiness (one file, one in-flight ticket); the index has no state of its own to collide on.</collision>")
    a("  </many-agents>")
    a("")
    a('  <sources id="sources">')
    a('    <source path="rebuild/design/dag.md" anchor="3-every-node" note="the node table this index is generated from"/>')
    a('    <source path="rebuild/factory-rebuild-plan.xml" anchor="R-03" note="the plan step that produces the book"/>')
    a('    <source path="rebuild/schema/factory-rebuild-plan.xsd" anchor="" note="the ancestor of schema/volume.xsd"/>')
    a('    <source path="rebuild/investigation/README.md" anchor="" note="the investigation index the DAG grew from"/>')
    a('    <source path="rebuild/investigation/BRIEF.md" anchor="" note="the investigation brief"/>')
    a('    <source path="rebuild/investigation/00-INVENTORY.md" anchor="" note="the inventory of everything the book touches"/>')
    a('    <source href="~/.local/state/coq/coq-jev-herdr-plugin/rebuild/2026/10/briefs/20261014-brief-C-design-spec-book.md" note="brief C: what R-03 produces"/>')
    a('    <source href="~/.claude/projects/-home-luna-projects-coq-jev-herdr-plugin/memory/spec-book-many-small-xml.md" note="unlimited volumes of 1000 lines or fewer, an index volume, pointers that resolve"/>')
    a("  </sources>")
    a("</volume>")
    return "\n".join(L) + "\n"


def main():
    text = render()
    target = os.path.join(BOOK, "index.xml")
    if "--check" in sys.argv:
        current = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        if current != text:
            print("FAIL C11 index.xml is stale; run rebuild/design/bin/make-index.py")
            return 1
        return 0
    with open(target, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s" % os.path.relpath(target, BOOK))
    return 0


if __name__ == "__main__":
    sys.exit(main())
