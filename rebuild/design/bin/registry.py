#!/usr/bin/env python3
"""
rebuild/design/bin/registry.py: generate rebuild/design/shared/cleanup-registry.json from the state-paths element of
every node volume, and check every entry has a way to be cleaned up.

What broke: shared/principles.xml#artifacts-out-of-repo and nodes/N-45/spec.xml#registry required every state path to be
an entry of shared/cleanup-registry.json generated by this script, and neither existed (gap review R-03, 2026-10-14);
several volumes named a path with no script at all ("not a cleanup target", "never by script", "Reset view"), which
brief C rule 6 and the owner's C35 order forbid unless the path is declared as kept on purpose.
Why this shape: the node volume that writes a path is the only author that knows it, so the registry is generated from
the volumes, never typed. The cleanup command stays what the volume names (scheduler/host/bin/cleanup-*.sh,
ci/bin/cleanup-ci-state.sh, tools/bearings/bin/cleanup-*.sh, tools/map/bin/cleanup.sh or line/bin/cleanup.sh itself),
and the service has one verb for all of them: line/bin/cleanup.sh --entry <id> looks the entry up here and runs that
command in plan, then apply, mode (N-45). Rejected: forcing every group onto one script now, which would rewrite five
groups' runbooks for no behaviour change and is a build ticket's job, not the design's. Cost: five script families
exist; the registry is the one list that names them all.

Entry fields: id, node, glob, class (host, store, client, external, tracked), retention (ISO 8601 duration, never,
or the volume's words), trigger, acts (system or owner), run (the command as the volume wrote it), verb, holds, note.
Class is the attribute class= when present, else inferred from the glob (store rows, browser storage, another system,
a tracked file in a repository, a host path).

Checks (one line "FAIL C14 <volume> <detail>" each):
  R1 every path element names a cleanup;
  R2 a host or external path whose cleanup names no script or retention mechanism declares retention="never" and
     acts="owner" (kept on purpose, removed only by the owner's break glass);
  R3 a tracked or client path declares retention="never" (tracked files leave by pull request, browser storage by the
     page's Reset view; neither is a host state path);
  R4 ids are unique across the book; R5 the committed registry equals the generated one (--check);
  R6 every entry validates against shared/cleanup-registry.schema.json (when the jsonschema module is importable).

Usage: bin/registry.py [--check]
"""
import glob
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

BOOK = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TARGET = os.path.join(BOOK, "shared", "cleanup-registry.json")
SCRIPT_RE = re.compile(r"(\S+\.(sh|py|mjs)\b|line/bin/cleanup\.sh|retention class|buildDiscarder|journalctl|vacuum|retention:)")
CLASSES = ("host", "store", "client", "external", "tracked")


def infer_class(glob_text, pid):
    g = glob_text.strip()
    low = g.lower()
    if pid.endswith(".store") or low.startswith("store ") or "store rows" in low or "store table" in low or "store view" in low \
            or re.search(r"\((table|tables|entity|entities)\b", low):
        return "store"
    if low.startswith("browser localstorage"):
        return "client"
    if low.startswith(("cluster:", "ghcr.io", "jenkins", "github", "journal", "podman ", "origin ", "exports:")):
        return "external"
    if low.startswith(("homelab-gitops:", "tools/", "rebuild/", "scheduler/config", "factory/")):
        return "tracked"
    return "host"


def slug(node, g):
    s = re.sub(r"^(\$\{?COQ_STATE\}?/|\$\{?COQ_CACHE\}?/|STATE/|~/|\$HOME/|XDG_RUNTIME_DIR/)", "", g.strip())
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return "%s.%s" % (node, s[:40].strip("-") or "path")


def collect():
    entries = []
    fails = []
    seen = {}
    for f in sorted(glob.glob(os.path.join(BOOK, "nodes", "N-*", "*.xml"))):
        try:
            root = ET.parse(f).getroot()
        except ET.ParseError:
            continue
        node = root.attrib.get("node") or os.path.basename(os.path.dirname(f))
        rel = os.path.relpath(f, BOOK)
        for sec in root.iter():
            if sec.attrib.get("id") != "state-paths":
                continue
            for p in sec.iter("path"):
                a = p.attrib
                g = a.get("glob") or a.get("p") or a.get("dir") or ""
                if not g:
                    fails.append((rel, "a path element has no glob, p or dir attribute"))
                    continue
                pid = a.get("id") or slug(node, g)
                base, n = pid, 2
                while pid in seen and not a.get("id"):
                    pid = "%s-%d" % (base, n)
                    n += 1
                if pid in seen:
                    fails.append((rel, "R4 id %s is also declared in %s" % (pid, seen[pid])))
                seen[pid] = rel
                cls = a.get("class") or infer_class(g, pid)
                if cls not in CLASSES:
                    fails.append((rel, "class %r of %s is not one of %s" % (cls, pid, ", ".join(CLASSES))))
                cleanup = (a.get("cleanup") or "").strip()
                retention = (a.get("retention") or "").strip()
                acts = a.get("acts", "system")
                if not cleanup:
                    fails.append((rel, "R1 %s names no cleanup" % pid))
                elif cls in ("host", "external") and not SCRIPT_RE.search(cleanup) and not (retention == "never" and acts == "owner"):
                    fails.append((rel, "R2 %s (%s) names no cleanup script; give it one or declare retention=\"never\" acts=\"owner\"" % (pid, g[:60])))
                if cls in ("tracked", "client") and retention != "never":
                    fails.append((rel, "R3 %s is class %s and must declare retention=\"never\"" % (pid, cls)))
                entries.append({
                    "id": pid,
                    "node": node,
                    "glob": g,
                    "class": cls,
                    "retention": retention or "as the run command applies",
                    "trigger": a.get("trigger", "timer"),
                    "acts": acts,
                    "run": cleanup,
                    "verb": "line/bin/cleanup.sh --entry %s" % pid,
                    "holds": a.get("holds", ""),
                    "note": " ".join("".join(p.itertext()).split())[:240],
                    "volume": rel,
                })
    return entries, fails


def render(entries):
    doc = {
        "generated_by": "rebuild/design/bin/registry.py",
        "schema": "shared/cleanup-registry.schema.json",
        "rule": "Every state path a node volume names, with the command that cleans it; line/bin/cleanup.sh --entry <id> is the one verb (N-45). Do not edit by hand.",
        "entries": entries,
    }
    # One entry per line: the file stays near one line per state path, and a diff shows exactly the paths that moved.
    head = json.dumps({k: v for k, v in doc.items() if k != "entries"}, ensure_ascii=True)[:-1]
    rows = ",\n".join("  " + json.dumps(e, ensure_ascii=True) for e in entries)
    return head + ', "entries": [\n' + rows + "\n]}\n"


def main():
    entries, fails = collect()
    text = render(entries)
    rc = 0
    for f, d in fails:
        print("FAIL C14 %s %s" % (f, d))
        rc = 1
    try:
        import jsonschema
        with open(os.path.join(BOOK, "shared", "cleanup-registry.schema.json"), encoding="utf-8") as fh:
            schema = json.load(fh)
        for err in jsonschema.Draft202012Validator(schema).iter_errors(json.loads(text)):
            print("FAIL C14 shared/cleanup-registry.json schema: %s at %s" % (err.message, "/".join(str(x) for x in err.path)))
            rc = 1
    except ImportError:
        pass
    if "--check" in sys.argv:
        current = open(TARGET, encoding="utf-8").read() if os.path.exists(TARGET) else ""
        if current != text:
            print("FAIL C14 shared/cleanup-registry.json is stale; run rebuild/design/bin/registry.py")
            rc = 1
        return rc
    with open(TARGET, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d entries)" % (os.path.relpath(TARGET, BOOK), len(entries)))
    return rc


if __name__ == "__main__":
    sys.exit(main())
