#!/usr/bin/env bash
# Generate rebuild/plan.json and rebuild/side.html, the two inputs the execution rail needs, from rebuild/factory-rebuild-plan.xml.
# Why one script makes both: the rail skill rule is "never put a fact on the page that is not in the plan or the ledger", so the side
# panels (status code map, build mode rule, failure cases, recovery) are read out of the XML and never hand-written. Rejected: a
# hand-edited side.html, which would drift from the XML the first time a code or a case changed.
# plan.json shape is fixed by the skill: ordered array of {id, t, who, gate, owner}. t is the step name, who is the owner-role,
# gate is the step's gate element, owner is true when the step's only model-class is owner (this makes R-02 the owner step).
# Usage: plan-to-rail.sh            validate, then write plan.json and side.html next to the XML.
#        plan-to-rail.sh --check    validate, then fail if the committed plan.json or side.html differ from what the XML generates.
# Exit 0 clean, 1 on any validation or drift error.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
base="$here/.."
mode="write"; [ "${1:-}" = "--check" ] && mode="check"
"$here/plan-validate.sh" >/dev/null
python3 - "$base" "$mode" <<'PY'
import json, sys, html
import xml.etree.ElementTree as ET
base, mode = sys.argv[1], sys.argv[2]
root = ET.parse(f"{base}/factory-rebuild-plan.xml").getroot()

plan = []
for s in root.find("steps").findall("step"):
    classes = [m.text for m in s.findall("model-class")]
    plan.append({
        "id": s.get("id"),
        "t": s.find("name").text,
        "who": s.find("owner-role").text,
        "gate": s.find("gate").text == "true",
        "owner": classes == ["owner"],
    })
plan_json = json.dumps(plan, indent=2, ensure_ascii=False) + "\n"

e = html.escape
def pc(title, line, foot=None):
    out = f'<div class="pc"><b>{e(title)}</b><span>{e(line)}</span>'
    if foot:
        out += f'<span class="f">{e(foot)}</span>'
    return out + "</div>"
def block(title, body):
    return f"<details><summary>{e(title)}</summary><div class=\"in\">{body}</div></details>\n"

side = "<!-- generated by rebuild/bin/plan-to-rail.sh from factory-rebuild-plan.xml, never hand-edited -->\n"
side += block("Status code map", "".join(
    pc(f'{c.get("value")} - {c.get("name")}', c.find("meaning").text, "acts: " + c.find("acts").text)
    for c in root.find("status-codes").findall("code")))
bm = next(p for p in root.find("principles").findall("principle") if p.get("id") == "build-mode")
side += block("Build mode rule", f'<p>{e(bm.find("quote").text)}</p><ul class="rules">' +
    "".join(f"<li>{e(x.text)}</li>" for x in bm.findall("statement")) + "</ul>")
side += block("Failure cases", "".join(
    pc(c.get("id"), c.find("meaning").text, "detect: " + c.find("detection").text + " recover: " + c.find("recovery").text +
       " acts: " + c.find("acts").text + f' retries: {c.find("retries").text}, then {c.find("then-status").text}')
    for c in root.find("failure-cases").findall("case")))
rec = root.find("recovery")
side += block("Recovery", f'<p>{e(rec.find("read-first").text)}</p><ul class="rules">' +
    "".join(f'<li>{e(f.get("order"))}. {e(f.get("path"))} - {e(f.text)}</li>' for f in rec.findall("file")) +
    f'</ul><p>{e(rec.find("rebuild-command").text)}</p><ul class="rules">' +
    "".join(f"<li>{e(a.text)}</li>" for a in rec.findall("action")) + "</ul>")

bad = 0
for name, text in (("plan.json", plan_json), ("side.html", side)):
    path = f"{base}/{name}"
    if mode == "write":
        open(path, "w", encoding="utf-8").write(text)
        print(f"plan-to-rail: wrote {name}")
    else:
        try:
            same = open(path, encoding="utf-8").read() == text
        except FileNotFoundError:
            same = False
        print(f"plan-to-rail: {name} {'matches' if same else 'DIFFERS from'} the XML")
        bad += 0 if same else 1
sys.exit(1 if bad else 0)
PY
