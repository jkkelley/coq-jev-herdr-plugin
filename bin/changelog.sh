#!/usr/bin/env bash
# changelog.sh - the change log as dated entry files, and CHANGELOG.md rendered from them.
# Owner order 2026-10-10 UTC: "change log too", and CHANGELOG.md is never edited by hand
# (~/.claude/CLAUDE.md). Every entry is one file on the dated-entry layout (AGENTS.md hard
# rule): changelog/YYYY/MM/YYYYMMDD-<name>.md with frontmatter; CHANGELOG.md is generated.
#
#   changelog.sh add    --type feat|fix|docs|chore|decision --title T [--ticket WO-...] [--sha S] [--text T] [--json]
#   changelog.sh render [--json]          writes CHANGELOG.md from every entry, newest first
#   changelog.sh check                    exit 3 when CHANGELOG.md is not what render would write, or an entry is malformed
#
# Exit codes: 0 ok, 2 usage, 3 validation, 4 io.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd); REPO=$(cd "$HERE/.." && pwd); TREE=$REPO/changelog; OUT=$REPO/CHANGELOG.md
die() { local c=$1; shift; printf 'changelog: %s\n' "$*" >&2; exit "$c"; }
slug() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//' | cut -c1-50 | sed -E 's/-+$//'; }
render() {
  echo "# Changelog"; echo
  echo "Generated by bin/changelog.sh render from changelog/YYYY/MM/*.md. Do not edit; add an entry with bin/changelog.sh add."; echo
  local f day cur=""
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    day=$(basename "$f" | cut -c1-8); day="${day:0:4}-${day:4:2}-${day:6:2}"
    [ "$day" = "$cur" ] || { cur=$day; echo "## $day"; echo; }
    awk -v f="${f#"$REPO"/}" '
      BEGIN{fm=0} /^---$/{fm++; next}
      fm==1 && /^title: /{t=substr($0,8)} fm==1 && /^type: /{ty=substr($0,7)} fm==1 && /^ticket: /{tk=substr($0,9)} fm==1 && /^sha: /{sha=substr($0,6)}
      fm>=2 && NF{body=body (body?" ":"") $0}
      END{line="- **" ty "** " t; if(tk!="" && tk!="null") line=line " (" tk ")"; if(sha!="" && sha!="null") line=line " `" sha "`"; if(body!="") line=line ": " body; print line " [entry](" f ")"}' "$f"
  done < <(find "$TREE" -name '*.md' 2>/dev/null | sort -r)
}
VERB=${1:-}; shift || true
case $VERB in
  add)
    type=""; title=""; ticket=""; sha=""; text=""; json=0
    while [ $# -gt 0 ]; do case $1 in --type) type=$2; shift 2;; --title) title=$2; shift 2;; --ticket) ticket=$2; shift 2;; --sha) sha=$2; shift 2;; --text) text=$2; shift 2;; --json) json=1; shift;; *) die 2 "unknown flag $1";; esac; done
    [[ $type =~ ^(feat|fix|docs|chore|decision)$ ]] || die 3 "bad type $type"; [ -n "$title" ] || die 2 "add needs --title"
    [ -z "$ticket" ] || [[ $ticket =~ ^WO-[0-9]{8}-[0-9a-f]{4}$ ]] || die 3 "bad ticket $ticket"
    at=$(date -u +%Y-%m-%dT%H:%M:%SZ); d=$(date -u +%Y%m%d); dir=$TREE/${d:0:4}/${d:4:2}; mkdir -p "$dir"
    name=$(slug "$title"); [ -n "$name" ] || die 3 "title slugs to nothing"
    path=$dir/$d-$name.md; [ -e "$path" ] && path=$dir/$d-$name-$(head -c 16 /dev/urandom | tr -dc a-z0-9 | head -c 5).md
    { printf -- '---\ntitle: %s\nat: %s\ntype: %s\nticket: %s\nsha: %s\n---\n' "$title" "$at" "$type" "${ticket:-null}" "${sha:-null}"; [ -n "$text" ] && printf '\n%s\n' "$text"; } > "$path.tmp" && mv "$path.tmp" "$path"
    render > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
    if [ "$json" = 1 ]; then jq -n --arg p "${path#"$REPO"/}" --arg at "$at" '{ok:true,path:$p,at:$at}'; else printf '%s\n' "${path#"$REPO"/}"; fi ;;
  render) render > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"; echo "wrote CHANGELOG.md" >&2 ;;
  check)
    bad=0
    for f in $(find "$TREE" -name '*.md' 2>/dev/null | sort); do
      b=$(basename "$f"); [[ $b =~ ^[0-9]{8}-[a-z0-9-]{1,50}(-[a-z0-9]{5})?\.md$ ]] || { echo "bad entry name $f" >&2; bad=1; }
      [[ $f =~ /changelog/[0-9]{4}/[0-9]{2}/ ]] || { echo "entry outside YYYY/MM: $f" >&2; bad=1; }
      for k in title at type; do grep -q "^$k: " "$f" || { echo "$f: frontmatter lacks $k" >&2; bad=1; }; done
      grep -q '^at: [0-9]\{4\}-[0-9]\{2\}-[0-9]\{2\}T[0-9]\{2\}:[0-9]\{2\}:[0-9]\{2\}Z$' "$f" || { echo "$f: at is not UTC ISO 8601 Z" >&2; bad=1; }
    done
    if [ -e "$OUT" ] || [ -d "$TREE" ]; then diff -q <(render) "$OUT" >/dev/null 2>&1 || { echo "CHANGELOG.md is stale: run bin/changelog.sh render" >&2; bad=1; }; fi
    [ "$bad" = 0 ] && echo "changelog ok" || exit 3 ;;
  *) sed -n '2,11p' "$0" >&2; exit 2 ;;
esac
